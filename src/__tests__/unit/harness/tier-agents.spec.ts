import { load } from 'js-yaml'
import { mkdir, mkdtemp, readFile, rm, writeFile } from 'fs/promises'
import { tmpdir } from 'os'
import { join } from 'path'

import { ADOPTION_COMMON_INSTRUCTIONS, GENERATED_REGION_END, GENERATED_REGION_START, installAgentInstructions } from '../../../harness/agent-instructions'
import { listTierAssignments, type RoutingOverrides } from '../../../harness/routing-grid'
import { TIER_AGENT_PATH, renderTierAgents } from '../../../harness/tier-agents'
import { hashFileContent } from '../../../utils'

const TIERS = ['light', 'edit', 'build', 'fix', 'plan', 'terminal']

function frontmatter(content: string): Record<string, unknown> {
  const match = /^---\n([\s\S]*?)\n---\n/.exec(content)
  if (!match) throw new Error('no frontmatter')
  return load(match[1]) as Record<string, unknown>
}

/** The renderer writes one `key = <JSON string>` per scalar and one multi-line developer_instructions. */
function toml(content: string): Record<string, string> {
  const entries = [...content.matchAll(/^(\w+) = ("(?:[^"\\]|\\.)*")$/gm)].map(([, key, value]) => [key, JSON.parse(value)])
  const instructions = /^developer_instructions = """\n([\s\S]*?)\n"""$/m.exec(content)
  return { ...Object.fromEntries(entries), ...(instructions ? { developer_instructions: instructions[1] } : {}) }
}

describe('tier agent rendering (#929)', () => {
  it('renders a Claude Code subagent per tier with the grid model and effort (AC-1)', () => {
    const files = renderTierAgents(['claude-code'])
    expect(files.map((file) => file.path)).toEqual(TIERS.map((tier) => `.claude/agents/sf-${tier}.md`))
    const fix = frontmatter(files[3].content)
    expect(fix).toEqual({ name: 'sf-fix', description: expect.any(String), model: 'claude-opus-5-5', effort: 'medium' })
    expect(files[3].content).toContain('Generated by SaaSFoundry from the routing grid v1')
    expect(files[3].content).toContain('Follow the project instructions in AGENTS.md')
  })

  it('renders a Codex custom agent per tier with model_reasoning_effort (AC-1)', () => {
    const files = renderTierAgents(['codex'])
    expect(files.map((file) => file.path)).toEqual(TIERS.map((tier) => `.codex/agents/sf-${tier}.toml`))
    const terminal = toml(files[5].content)
    expect(terminal).toEqual({
      name: 'sf-terminal',
      description: expect.any(String),
      model: 'gpt-6.1-sol',
      model_reasoning_effort: 'high',
      developer_instructions: expect.stringContaining('terminal tier delegate')
    })
    for (const file of files) expect(file.path).toMatch(TIER_AGENT_PATH)
  })

  it('says which kinds a tier serves and which tier to use instead (AC-3)', () => {
    const description = String(frontmatter(renderTierAgents(['claude-code'])[0].content).description)
    expect(description).toContain('Use for exploration (read-only codebase search and questions), prose (documentation and other prose).')
    expect(description).toContain('Do not use for scoped-edit (use sf-edit); bug-fix, review (use sf-fix); multi-file-feature, tests (use sf-build); planning (use sf-plan)')
    expect(description).toContain('terminal-ci (use sf-terminal).')
  })

  it('renders only for declared hosts the grid routes (AC-2)', () => {
    expect(renderTierAgents(['gemini-cli', 'kimi'])).toEqual([])
    expect(renderTierAgents(['codex', 'gemini-cli']).every((file) => file.path.startsWith('.codex/'))).toBe(true)
  })

  it('reflects project overrides and marks their origin', () => {
    const overrides: RoutingOverrides = { kinds: { 'terminal-ci': { tier: 'plan' } }, tiers: { plan: { 'claude-code': { model: 'claude-sonnet-5-5', effort: 'max' } } } }
    const files = renderTierAgents(['claude-code'], overrides)
    expect(files.map((file) => file.path)).not.toContain('.claude/agents/sf-terminal.md')
    const plan = files.find((file) => file.path === '.claude/agents/sf-plan.md')!
    expect(frontmatter(plan.content)).toMatchObject({ model: 'claude-sonnet-5-5', effort: 'max' })
    expect(plan.content).toContain('Generated by SaaSFoundry from the modules.harness.routing')
    expect(String(frontmatter(plan.content).description)).toContain('Use for planning (')
  })

  it('names an excluded candidate the project routes a kind to', () => {
    const overrides: RoutingOverrides = { tiers: { terminal: { 'claude-code': { model: 'claude-haiku-5-5', effort: 'max' } } } }
    expect(listTierAssignments('claude-code', overrides).find((entry) => entry.tier === 'terminal')?.excludedFor).toEqual(['terminal-ci'])
    expect(renderTierAgents(['claude-code'], overrides).find((file) => file.path.endsWith('sf-terminal.md'))?.content).toContain('although the grid excludes this candidate')
  })
})

describe('tier agent deposits (#929)', () => {
  let root: string
  const get = (path: string) => readFile(join(root, path), 'utf8')
  const tierPaths = (paths: string[]) => paths.filter((path) => TIER_AGENT_PATH.test(path))

  beforeEach(async () => {
    root = await mkdtemp(join(tmpdir(), 'sf-tier-agents-'))
    await writeFile(join(root, 'AGENTS.md'), `# Project\n\n${GENERATED_REGION_START}\n${GENERATED_REGION_END}\n`)
  })
  afterEach(async () => {
    await rm(root, { recursive: true, force: true })
  })

  it('deposits hash-tracked tier agents for each declared host and is idempotent (AC-2, AC-4)', async () => {
    const first = await installAgentInstructions({ targetPath: root, agents: ['claude-code', 'codex'] })
    expect(tierPaths(first.written)).toHaveLength(12)
    for (const path of tierPaths(first.written)) expect(first.fileHashes[path]).toBe(hashFileContent(await get(path)))
    const second = await installAgentInstructions({ targetPath: root, agents: ['claude-code', 'codex'], manifest: { fileHashes: first.fileHashes } })
    expect(tierPaths(second.written)).toEqual([])
    expect(tierPaths(second.unchanged)).toHaveLength(12)
  })

  it('refreshes an untouched tier agent when the routing changes, and keeps an edited one behind a sidecar', async () => {
    const first = await installAgentInstructions({ targetPath: root, agents: ['claude-code'] })
    await writeFile(join(root, '.claude/agents/sf-fix.md'), '---\nname: sf-fix\ndescription: mine\nmodel: opus\n---\n')
    const routing: RoutingOverrides = { tiers: { light: { 'claude-code': { model: 'claude-sonnet-5-5', effort: 'low' } }, fix: { 'claude-code': { model: 'claude-sonnet-5-5', effort: 'high' } } } }
    const second = await installAgentInstructions({ targetPath: root, agents: ['claude-code'], manifest: { fileHashes: first.fileHashes, modules: { harness: { routing } } } })
    expect(second.written).toContain('.claude/agents/sf-light.md')
    expect(frontmatter(await get('.claude/agents/sf-light.md'))).toMatchObject({ model: 'claude-sonnet-5-5', effort: 'low' })
    expect(second.conflicts).toEqual(['.claude/agents/sf-fix.md'])
    expect(await get('.claude/agents/sf-fix.md')).toContain('description: mine')
    expect(frontmatter(await get('.claude/agents/sf-fix.md.saasfoundry.new'))).toMatchObject({ effort: 'high' })
  })

  it('warns instead of failing when the routing override cannot be resolved for a declared host', async () => {
    const routing = { kinds: { prose: { tier: 'docs' } }, tiers: { docs: { codex: { model: 'gpt-6-luna', effort: 'low' } } } } as RoutingOverrides
    const result = await installAgentInstructions({ targetPath: root, agents: ['claude-code'], manifest: { modules: { harness: { routing } } } })
    expect(tierPaths(result.written)).toEqual([])
    expect(result.warnings.join('\n')).toContain("Tier agents not generated: Tier 'docs' has no claude-code candidate")
  })

  it('adds no tier agent to an adopted project, which only references its own setup', async () => {
    await mkdir(join(root, '.claude'), { recursive: true })
    const result = await installAgentInstructions({
      targetPath: root,
      agents: ['claude-code'],
      referenceOnly: true,
      manifest: { fileHashes: { 'AGENTS.md': hashFileContent(ADOPTION_COMMON_INSTRUCTIONS) } }
    })
    expect(tierPaths([...result.written, ...result.unchanged])).toEqual([])
  })
})
