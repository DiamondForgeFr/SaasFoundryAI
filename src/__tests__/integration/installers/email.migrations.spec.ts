/**
 * #976 — the email module v1 → v2 migration: a project generated before the mail catcher gets, from
 * `sf update`, what a project generated with it has.
 *
 * The project under test is a real one: the API blueprint with the email module installed, then
 * taken back to what v1 deposited (the v1 service from a fixture, the schema without the variable,
 * a `.env` and a compose file without the catcher). The migrated result is compared with a fresh
 * render, byte for byte: any difference would show up as a conflict nobody made in the template
 * update that follows `sf update`.
 */

const PROJECT = 'acme'
const V1_SERVICE = resolve(__dirname, '../../fixtures/email-v1/mailersend.service.ts.fixture')
const CATCHER_SCHEMA = `    ${MAIL_CATCHER_SCHEMA_COMMENT}\n    ${MAIL_CATCHER_SCHEMA_ENTRY}\n`

type Topology = 'multirepo' | 'monorepo'

interface Fixture {
  root: string
  apiDir: string
  manifest: SaaSFoundryManifest
  path: (relative: string) => string
  read: (relative: string) => Promise<string>
}

const roots: string[] = []
afterAll(async () => {
  await Promise.all(roots.map((root) => rm(root, { recursive: true, force: true }).catch(() => {})))
})

// The migration reports what it did; the specs read it back where they assert it
let log: jest.SpyInstance
beforeEach(() => {
  log = jest.spyOn(console, 'log').mockImplementation(() => {})
})
afterEach(() => {
  log.mockRestore()
})

/** The project as the 1.3.0 CLI left it: email module installed, no catcher anywhere. */
async function v1Project(topology: Topology, { compose = true, ports = { db: 5435, api: 3500, web: 5173 } }: { compose?: boolean; ports?: SaaSFoundryManifest['ports'] } = {}): Promise<Fixture> {
  const root = await mkdtemp(join(tmpdir(), 'sf-email-migration-'))
  roots.push(root)
  const isMonorepo = topology === 'monorepo'
  const apiDir = isMonorepo ? 'apps/api' : `apps/${PROJECT}-api`
  const apiPath = join(root, apiDir)

  await copy(resolve(blueprintsPath, 'api'), apiPath)
  // A monorepo's shared-types workspace is what the installer rewires the service to
  if (isMonorepo) {
    await mkdir(join(root, 'packages/shared-types/src'), { recursive: true })
    await writeFile(join(root, 'packages/shared-types/src/index.ts'), "export * from './common'\n")
  }
  await installEmailModule({ apiPath, isMonorepo, projectName: PROJECT, mailersendApiKey: 'ms_key', mailersendSenderEmail: 'noreply@acme.test', mailersendSenderName: 'Acme' })

  // Back to v1: the service, the schema and the `.env` as they were before the catcher
  const v1Service = await readFile(V1_SERVICE, 'utf8')
  await writeFile(join(apiPath, 'src/modules/email/services/mailersend.service.ts'), isMonorepo ? rewireMailerSendToSharedTypes(v1Service, PROJECT) : v1Service)
  const schema = await readFile(join(apiPath, 'src/configs/env/services/env.service.ts'), 'utf8')
  expect(schema).toContain(CATCHER_SCHEMA)
  await writeFile(join(apiPath, 'src/configs/env/services/env.service.ts'), schema.replace(CATCHER_SCHEMA, ''))
  const env = await readFile(join(apiPath, '.env'), 'utf8')
  await writeFile(join(apiPath, '.env'), env.replace(/^MAIL_CATCHER_URL=.*\n/m, ''))
  if (compose) await createDevServicesCompose({ apiPath, projectName: PROJECT, dbSetup: 'docker', s3Setup: 'manual' })

  const manifest: SaaSFoundryManifest = {
    version: '1.3.0',
    generatedAt: '2026-11-01T00:00:00.000Z',
    structure: topology,
    projectName: PROJECT,
    ports,
    modules: { email: { provider: 'mailersend', version: 1 }, s3Setup: 'manual', dbSetup: 'docker', includeAnalytics: false, advancedSkills: [] },
    fileHashes: await computeFileHashes(root)
  }
  return { root, apiDir, manifest, path: (relative) => join(root, apiDir, relative), read: (relative) => readFile(join(root, apiDir, relative), 'utf8') }
}

/** The same project generated by the current CLI: what the migration has to reach. */
async function freshProject(topology: Topology, mailPort: number): Promise<Fixture> {
  const root = await mkdtemp(join(tmpdir(), 'sf-email-fresh-'))
  roots.push(root)
  const isMonorepo = topology === 'monorepo'
  const apiDir = isMonorepo ? 'apps/api' : `apps/${PROJECT}-api`
  const apiPath = join(root, apiDir)
  await copy(resolve(blueprintsPath, 'api'), apiPath)
  if (isMonorepo) {
    await mkdir(join(root, 'packages/shared-types/src'), { recursive: true })
    await writeFile(join(root, 'packages/shared-types/src/index.ts'), "export * from './common'\n")
  }
  await installEmailModule({
    apiPath,
    isMonorepo,
    projectName: PROJECT,
    mailersendApiKey: 'ms_key',
    mailersendSenderEmail: 'noreply@acme.test',
    mailersendSenderName: 'Acme',
    mailCatcherPort: mailPort
  })
  await createDevServicesCompose({ apiPath, projectName: PROJECT, dbSetup: 'docker', s3Setup: 'manual', mailCatcher: { port: mailPort } })
  return { root, apiDir, manifest: {} as SaaSFoundryManifest, path: (relative) => join(root, apiDir, relative), read: (relative) => readFile(join(root, apiDir, relative), 'utf8') }
}

const SERVICE = 'src/modules/email/services/mailersend.service.ts'
const SCHEMA = 'src/configs/env/services/env.service.ts'
const COMPOSE = 'docker-compose.dev-services.yml'

const mailPortOf = (compose: string): number => Number(/- '(\d+):8025'/.exec(compose)?.[1])

describe.each(['multirepo', 'monorepo'] as const)('email v1 → v2 on a %s project (#976)', (topology) => {
  it('gives it what a fresh project has, byte for byte', async () => {
    const project = await v1Project(topology, { ports: { db: 5435, api: 3500, web: 5173, mail: 8099 } })

    const patch = await addDevMailCatcher.up(project.root, project.manifest)

    const fresh = await freshProject(topology, 8099)
    expect(await project.read(SERVICE)).toBe(await fresh.read(SERVICE))
    expect(await project.read(SCHEMA)).toBe(await fresh.read(SCHEMA))
    expect(await project.read(COMPOSE)).toBe(await fresh.read(COMPOSE))
    expect(mailPortOf(await project.read(COMPOSE))).toBe(8099)
    expect(await project.read('.env')).toContain('MAIL_CATCHER_URL=http://localhost:8099')
    expect(patch).toMatchObject({ ports: { db: 5435, api: 3500, web: 5173, mail: 8099 } })
  })

  it('keeps the monorepo form of the service, which imports its envelope from shared-types', async () => {
    const project = await v1Project(topology, { ports: { db: 5435, api: 3500, web: 5173, mail: 8099 } })

    await addDevMailCatcher.up(project.root, project.manifest)

    const service = await project.read(SERVICE)
    expect(service).toContain('MAIL_CATCHER_URL')
    if (topology === 'monorepo') expect(service).toContain(`from '@${PROJECT}/shared-types'`)
    else expect(service).toContain('export interface EmailOptions')
  })

  it('names the same port in the compose, the .env and the manifest patch when it chooses one', async () => {
    const project = await v1Project(topology)

    const patch = await addDevMailCatcher.up(project.root, project.manifest)

    const port = mailPortOf(await project.read(COMPOSE))
    expect(port).toBeGreaterThanOrEqual(8025)
    expect(await project.read('.env')).toContain(`MAIL_CATCHER_URL=http://localhost:${port}`)
    expect(patch).toMatchObject({ ports: { mail: port } })
    // The ports the project already runs on are carried over, not reset
    expect(patch).toMatchObject({ ports: { db: 5435, api: 3500, web: 5173 } })
  })

  it('hands back the new baseline of every file it rewrote, so the template update sees no edit', async () => {
    const project = await v1Project(topology, { ports: { db: 5435, api: 3500, web: 5173, mail: 8099 } })

    const patch = await addDevMailCatcher.up(project.root, project.manifest)

    const rewritten = [SERVICE, SCHEMA, COMPOSE].map((path) => `${project.apiDir}/${path}`)
    expect(Object.keys(patch?.fileHashes ?? {}).sort()).toEqual(rewritten.sort())
    for (const path of rewritten) expect(patch?.fileHashes?.[path]).toBe(hashFileContent(await readFile(join(project.root, path))))
  })

  it('is idempotent: a second run changes nothing and keeps the port', async () => {
    const project = await v1Project(topology)
    const first = await addDevMailCatcher.up(project.root, project.manifest)
    const files = await Promise.all([SERVICE, SCHEMA, COMPOSE, '.env'].map((path) => project.read(path)))

    const second = await addDevMailCatcher.up(project.root, { ...project.manifest, ports: first?.ports, fileHashes: { ...project.manifest.fileHashes, ...first?.fileHashes } })

    expect(await Promise.all([SERVICE, SCHEMA, COMPOSE, '.env'].map((path) => project.read(path)))).toEqual(files)
    expect(second?.ports).toEqual(first?.ports)
    expect(second?.fileHashes).toEqual({})
  })

  it('keeps an edited service and proposes the new one beside it, with the schema it needs', async () => {
    const project = await v1Project(topology, { ports: { db: 5435, api: 3500, web: 5173, mail: 8099 } })
    const edited = `${await project.read(SERVICE)}\n// the team's own retry policy\n`
    await writeFile(project.path(SERVICE), edited)

    const patch = await addDevMailCatcher.up(project.root, project.manifest)

    expect(await project.read(SERVICE)).toBe(edited)
    expect(await project.read(`${SERVICE}.saasfoundry.new`)).toBe(await (await freshProject(topology, 8099)).read(SERVICE))
    expect(await project.read(SCHEMA)).toContain('MAIL_CATCHER_URL')
    // The edited file keeps its old baseline: it is still the user's
    expect(patch?.fileHashes).not.toHaveProperty([`${project.apiDir}/${SERVICE}`])
  })

  it('moves the service and the schema together: an edited schema holds the service back too', async () => {
    const project = await v1Project(topology, { ports: { db: 5435, api: 3500, web: 5173, mail: 8099 } })
    const v1Service = await project.read(SERVICE)
    const edited = `${await project.read(SCHEMA)}\n// a variable of ours\n`
    await writeFile(project.path(SCHEMA), edited)

    await addDevMailCatcher.up(project.root, project.manifest)

    // A service that reads MAIL_CATCHER_URL does not compile against a schema that does not declare it
    expect(await project.read(SCHEMA)).toBe(edited)
    expect(await project.read(SERVICE)).toBe(v1Service)
    expect(await project.read(`${SCHEMA}.saasfoundry.new`)).toContain(MAIL_CATCHER_SCHEMA_ENTRY)
    expect(existsSync(project.path(`${SERVICE}.saasfoundry.new`))).toBe(true)
  })

  it('treats a file the manifest never tracked as the user’s, not as a new one', async () => {
    const project = await v1Project(topology, { ports: { db: 5435, api: 3500, web: 5173, mail: 8099 } })
    const v1Service = await project.read(SERVICE)
    const fileHashes = { ...project.manifest.fileHashes }
    delete fileHashes[`${project.apiDir}/${SERVICE}`]

    await addDevMailCatcher.up(project.root, { ...project.manifest, fileHashes })

    expect(await project.read(SERVICE)).toBe(v1Service)
    expect(existsSync(project.path(`${SERVICE}.saasfoundry.new`))).toBe(true)
  })

  it('creates the dev-services compose of a project that hosts neither the database nor the storage', async () => {
    const project = await v1Project(topology, { compose: false, ports: { db: 5435, api: 3500, web: 5173, mail: 8099 } })

    const patch = await addDevMailCatcher.up(project.root, project.manifest)

    const compose = await project.read(COMPOSE)
    expect(mailPortOf(compose)).toBe(8099)
    expect(compose).not.toContain('db-dev')
    expect(patch?.fileHashes).toHaveProperty([`${project.apiDir}/${COMPOSE}`])
  })

  it('keeps a MAIL_CATCHER_URL the developer already set', async () => {
    const project = await v1Project(topology, { ports: { db: 5435, api: 3500, web: 5173, mail: 8099 } })
    await writeFile(project.path('.env'), `${await project.read('.env')}\nMAIL_CATCHER_URL=http://mailhog:8025\n`)

    await addDevMailCatcher.up(project.root, project.manifest)

    expect(await project.read('.env')).toContain('MAIL_CATCHER_URL=http://mailhog:8025')
    expect(await project.read('.env')).not.toContain('localhost:8099')
  })

  it('leaves a project without a dev `.env` alone: the file is a local one, a fresh clone has none', async () => {
    const project = await v1Project(topology, { ports: { db: 5435, api: 3500, web: 5173, mail: 8099 } })
    await rm(project.path('.env'))

    await addDevMailCatcher.up(project.root, project.manifest)

    expect(existsSync(project.path('.env'))).toBe(false)
    expect(mailPortOf(await project.read(COMPOSE))).toBe(8099)
  })

  it('says what it could not change instead of guessing: a schema without the sender line, a compose of another shape', async () => {
    const project = await v1Project(topology, { ports: { db: 5435, api: 3500, web: 5173, mail: 8099 } })
    const schema = (await project.read(SCHEMA)).replace('MAILERSEND_SENDER_NAME: z.string(),', 'MAILERSEND_SENDER_NAME: z.string().min(1),')
    const compose = 'name: acme\nservices:\n    cache:\n        image: redis:7\n'
    await writeFile(project.path(SCHEMA), schema)
    await writeFile(project.path(COMPOSE), compose)
    await addDevMailCatcher.up(project.root, project.manifest)

    const printed = log.mock.calls.flat().join('\n')
    expect(printed).toContain('Could not change these files safely')
    expect(printed).toContain(`${project.apiDir}/${SCHEMA}`)
    expect(printed).toContain(`${project.apiDir}/${COMPOSE}`)
    expect(await project.read(SCHEMA)).toBe(schema)
    expect(await project.read(COMPOSE)).toBe(compose)
    // The service waits for a schema that declares the variable
    expect(await project.read(SERVICE)).not.toContain('MAIL_CATCHER_URL')
    expect(existsSync(project.path(`${SERVICE}.saasfoundry.new`))).toBe(true)
  })
})

describe('email v1 → v2 on a project that has no mailer (#976)', () => {
  it('changes nothing', async () => {
    const project = await v1Project('multirepo')
    await rm(project.path(SERVICE))
    const before = await Promise.all([SCHEMA, COMPOSE, '.env'].map((path) => project.read(path)))

    expect(await addDevMailCatcher.up(project.root, { ...project.manifest, modules: { ...project.manifest.modules, email: { provider: 'none', version: 1 } } })).toBeUndefined()

    expect(await Promise.all([SCHEMA, COMPOSE, '.env'].map((path) => project.read(path)))).toEqual(before)
  })

  it('has nothing to preview', async () => {
    const project = await v1Project('multirepo')
    await rm(project.path(SERVICE))

    expect(await addDevMailCatcher.preview?.(project.root, project.manifest)).toEqual([])
  })

  it('does nothing for a project with no API app', async () => {
    const root = await mkdtemp(join(tmpdir(), 'sf-email-cli-'))
    roots.push(root)
    expect(await addDevMailCatcher.up(root, { version: '1.3.0', generatedAt: '', structure: 'cli', projectName: 'tool', modules: { email: { provider: 'none', version: 1 } } })).toBeUndefined()
  })
})

describe('email v1 → v2 preview (#976)', () => {
  it('lists every file the migration would change, and what it would record, without touching any', async () => {
    const project = await v1Project('multirepo')
    const before = await Promise.all([SERVICE, SCHEMA, COMPOSE, '.env'].map((path) => project.read(path)))

    const preview = await addDevMailCatcher.preview?.(project.root, project.manifest)

    expect(preview?.map(({ action, source }) => `${action} ${source}`)).toEqual([
      `update ${project.apiDir}/${SCHEMA}`,
      `update ${project.apiDir}/${SERVICE}`,
      `update ${project.apiDir}/${COMPOSE}`,
      `update ${project.apiDir}/.env`,
      'update .saasfoundry.json#ports'
    ])
    expect(await Promise.all([SERVICE, SCHEMA, COMPOSE, '.env'].map((path) => project.read(path)))).toEqual(before)
  })

  it('has nothing to preview once the project has the catcher', async () => {
    const project = await v1Project('multirepo', { ports: { db: 5435, api: 3500, web: 5173, mail: 8099 } })
    await addDevMailCatcher.up(project.root, project.manifest)

    expect(await addDevMailCatcher.preview?.(project.root, { ...project.manifest, modules: { ...project.manifest.modules } })).toEqual([])
  })
})

describe('email v1 → v2 through the dispatcher (#976)', () => {
  it('stamps the module at its current version, records the port and the new baselines, and leaves the input alone', async () => {
    const project = await v1Project('multirepo', { ports: { db: 5435, api: 3500, web: 5173, mail: 8099 } })
    const input = JSON.parse(JSON.stringify(project.manifest)) as SaaSFoundryManifest

    const { applied, manifest } = await runModuleMigrations(project.manifest, project.root)

    expect(applied).toEqual([{ module: 'email', fromVersion: 1, toVersion: emailInstallerMeta.currentVersion, migrations: ['add-dev-mail-catcher'] }])
    expect(manifest.modules?.email).toEqual({ provider: 'mailersend', version: 2 })
    expect(manifest.ports).toEqual({ db: 5435, api: 3500, web: 5173, mail: 8099 })
    expect(manifest.fileHashes?.[`${project.apiDir}/${SERVICE}`]).toBe(hashFileContent(await readFile(project.path(SERVICE))))
    // Untouched files keep the baseline they had
    expect(manifest.fileHashes?.[`${project.apiDir}/package.json`]).toBe(project.manifest.fileHashes?.[`${project.apiDir}/package.json`])
    expect(project.manifest).toEqual(input)
  })

  it('is a no-op on a project already at v2', async () => {
    const project = await v1Project('multirepo', { ports: { db: 5435, api: 3500, web: 5173, mail: 8099 } })
    const manifest: SaaSFoundryManifest = { ...project.manifest, modules: { ...project.manifest.modules, email: { provider: 'mailersend', version: 2 } } }
    const before = await project.read(SERVICE)

    const result = await runModuleMigrations(manifest, project.root)

    expect(result.applied).toEqual([])
    expect(result.manifest).toBe(manifest)
    expect(await project.read(SERVICE)).toBe(before)
  })
})

describe('the schema line the migration adds is the one the blueprint ships (#976)', () => {
  const blueprint = resolve(blueprintsPath, 'api', SCHEMA)

  it('equals the blueprint once its mailer markers are stripped, right after the sender', async () => {
    const stripped = (await readFile(blueprint, 'utf8')).replace(/\/\/ TODO mailer-service-active: /g, '')
    const withoutCatcher = stripped.replace(CATCHER_SCHEMA, '')

    expect(stripped).toContain(`MAILERSEND_SENDER_NAME: z.string(),\n${CATCHER_SCHEMA}`)
    expect(addMailCatcherToEnvSchema(withoutCatcher)).toBe(stripped)
  })

  it('adds nothing twice, and refuses a schema it cannot anchor in', () => {
    const once = addMailCatcherToEnvSchema('    MAILERSEND_SENDER_NAME: z.string(),\n')
    expect(once).toBe(`    MAILERSEND_SENDER_NAME: z.string(),\n${CATCHER_SCHEMA}`)
    expect(addMailCatcherToEnvSchema(once as string)).toBe(once)
    expect(addMailCatcherToEnvSchema('    JWT_SECRET_AUTH: z.string(),\n')).toBeNull()
  })

  it('stays commented out in a project without the email module', async () => {
    const source = await readFile(blueprint, 'utf8')
    const lines = source.split('\n').filter((line) => line.includes('MAIL_CATCHER_URL'))

    expect(lines.length).toBeGreaterThan(0)
    for (const line of lines) expect(line.trimStart()).toMatch(/^\/\/ TODO mailer-service-active: /)
  })
})
