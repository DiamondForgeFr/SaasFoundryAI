/**
 * Regenerate src/harness/released-bridge-hashes.ts: the sha256 of every generated instruction bridge a
 * published release wrote (#935). The bridges are generated text (`COMMON_INSTRUCTIONS` and its
 * siblings) and that text changes with the CLI, so a project installed by a release carries bytes
 * the running CLI no longer renders: only these hashes keep them recognised as generated.
 *
 * The bytes come from the fixtures captured from each published package (see the README next to
 * them). Adding a release is: capture its fixtures, then regenerate this table.
 *
 * Usage: npx tsx scripts/released-bridge-hashes.ts > src/harness/released-bridge-hashes.ts
 */
import { createHash } from 'crypto'
import { existsSync, readdirSync, readFileSync } from 'fs'
import { join } from 'path'

const FIXTURES = join(__dirname, '..', 'src', '__tests__', 'fixtures', 'released-bridges')
const KINDS = {
  common: 'AGENTS.common.md',
  adoption: 'AGENTS.adoption.md',
  claudeBridge: 'CLAUDE.bridge.md'
} as const

const versions = readdirSync(FIXTURES, { withFileTypes: true })
  .filter((entry) => entry.isDirectory() && /^\d+\.\d+\.\d+$/.test(entry.name))
  .map((entry) => entry.name)
  .sort((a, b) => a.localeCompare(b, undefined, { numeric: true }))

const table: Record<string, Record<string, string>> = {}
for (const [kind, file] of Object.entries(KINDS)) {
  table[kind] = {}
  for (const version of versions) {
    const path = join(FIXTURES, version, file)
    // A release that predates a bridge never wrote it: no fixture, no entry.
    if (existsSync(path)) table[kind][version] = createHash('sha256').update(readFileSync(path)).digest('hex')
  }
}

process.stdout.write(`// Generated by scripts/released-bridge-hashes.ts (#935) — do not edit by hand.

export type BridgeKind = 'common' | 'adoption' | 'claudeBridge'

/** Per bridge, per published release: the sha256 of the bytes that release wrote. */
export const RELEASED_BRIDGE_HASHES: Record<BridgeKind, Record<string, string>> = ${JSON.stringify(table, null, 2)}
`)
