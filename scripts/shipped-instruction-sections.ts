/**
 * Regenerate src/harness/shipped-instruction-sections.ts: the sha256 of every section each
 * pre-#937 CLAUDE.md template ever shipped (#938). The harness v3 → v4 migration treats a section
 * still matching one of these as SaaSFoundry's, and anything else as the user's.
 *
 * Sections whose installed bytes depend on the project (placeholders, rewritten ports) are left
 * out: they can never be recognised, so they always move verbatim.
 *
 * Usage: npx tsx scripts/shipped-instruction-sections.ts > src/harness/shipped-instruction-sections.ts
 */
import { execFileSync } from 'child_process'

import { sectionHash, splitSections } from '../src/harness/markdown-sections'

/** The last commit before #937 renamed the templates to AGENTS.md. */
const LAST_CLAUDE_MD_COMMIT = '2c6a3854^'
const TEMPLATES = {
  harness: 'scaffolds/skills-templates/harness/CLAUDE.md',
  api: 'scaffolds/blueprints/api/CLAUDE.md',
  web: 'scaffolds/blueprints/web/CLAUDE.md',
  monorepo: 'scaffolds/overlays/monorepo/root/CLAUDE.md'
}
const PROJECT_DEPENDENT = /\{\{|\b(3000|3500|5173)\b/

const git = (...args: string[]): string => execFileSync('git', args, { encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 })

const tables: Record<string, Record<string, string[]>> = {}
for (const [kind, template] of Object.entries(TEMPLATES)) {
  const byHeading = new Map<string, Set<string>>()
  for (const commit of git('log', '--format=%H', LAST_CLAUDE_MD_COMMIT, '--', template).split('\n').filter(Boolean)) {
    let content: string
    try {
      content = git('show', `${commit}:${template}`)
    } catch {
      continue // the commit deleted or renamed the file
    }
    for (const section of splitSections(content)) {
      if (!section.heading || PROJECT_DEPENDENT.test(section.text)) continue
      byHeading.set(section.heading, (byHeading.get(section.heading) ?? new Set()).add(sectionHash(section.text)))
    }
  }
  tables[kind] = Object.fromEntries([...byHeading.entries()].sort(([a], [b]) => a.localeCompare(b)).map(([heading, hashes]) => [heading, [...hashes].sort()]))
}

process.stdout.write(`// Generated by scripts/shipped-instruction-sections.ts (#938) — do not edit by hand.

export type TemplateKind = 'harness' | 'api' | 'web' | 'monorepo'

/** Per template, per \`##\` heading: the sha256 (see sectionHash) of every version a pre-#937 CLAUDE.md shipped. */
export const SHIPPED_SECTIONS: Record<TemplateKind, Record<string, string[]>> = ${JSON.stringify(tables, null, 2)}
`)
